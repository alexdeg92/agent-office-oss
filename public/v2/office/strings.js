export const STRINGS = { fr, en };

/**
 * s('office.error', { n: 2, names }) → picks `office.error.one|other` (Intl.PluralRules) when the plain key is
 * missing; parameters are named ({n}, {name}…). Unknown keys return the key (and are caught by the tests).
 */
export function s(key, params = {}, loc = locale()) {
  const dict = STRINGS[loc] ?? fr;
  let tpl = dict[key];
  if (tpl == null && 'n' in params) {
    if (Number(params.n) === 0 && dict[`${key}.zero`] != null) tpl = dict[`${key}.zero`];
    const cat = new Intl.PluralRules(intlLocale(loc)).select(Number(params.n));
    tpl ??= dict[`${key}.${cat}`] ?? dict[`${key}.other`];
  }
  if (tpl == null) tpl = fr[key] ?? key;
  return tpl.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** « Scout, Plume et Atlas » / “Scout, Plume and Atlas”. */
export const list = (items, loc = locale()) => new Intl.ListFormat(intlLocale(loc), { style: 'long', type: 'conjunction' }).format(items);

/** A duration in words: « 12 minutes », « 2 heures », « 3 jours » (largest unit, rounded down). */
export function duration(ms, loc = locale()) {
  const units = [['day', 86_400_000], ['hour', 3_600_000], ['minute', 60_000]];
  for (const [unit, size] of units) {
    if (ms >= size) return new Intl.NumberFormat(intlLocale(loc), { style: 'unit', unit, unitDisplay: 'long' }).format(Math.floor(ms / size));
  }
  return s('office.underMinute', {}, loc);
}

