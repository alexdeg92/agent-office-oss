/** For the test: every key defined more than once across the base registry and the page-owned parts. */
export const duplicateKeys = (l) => {
  const seen = new Set(); const dup = [];
  for (const part of [BASE[l], ...PARTS.map((p) => p[l])]) for (const k of Object.keys(part)) { if (seen.has(k)) dup.push(k); seen.add(k); }
  return dup;
};

/** Register a lazy page dictionary without adding it to other pages’ first load. */
export function registerMessages(part) {
  if (PARTS.includes(part)) return;
  PARTS.push(part);
  for (const l of Object.keys(MESSAGES)) Object.assign(MESSAGES[l], part[l]);
}
