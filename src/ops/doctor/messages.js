const CATALOG = { fr, en };
function format(locale, key, params = {}) {
  const t = (CATALOG[locale] || fr)[key] || fr[key] || key;
  return t.replace(/\{(\w+)\}/g, (m, k) => (params[k] === undefined || params[k] === null ? m : String(params[k])));
}

