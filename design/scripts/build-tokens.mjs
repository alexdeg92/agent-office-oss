#!/usr/bin/env node
// Bureau — generate design/css/bureau.css from design/tokens.json.
// Plain Node (>=18), no dependencies. Usage: node design/scripts/build-tokens.mjs
//
// Output:
//   :root / [data-theme="dark"]      dark colours (default) + every non-colour token
//   prefers-color-scheme: light      light colours unless the page forces data-theme="dark"
//   [data-theme="light"]             light colours (forced)
//   prefers-reduced-motion: reduce   durations collapse to ~0
//
// Motion is not a tokens.json family (see the brief); its values live in MOTION below
// and are documented in design/README.md § Mouvement. Keep the two in sync.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'tokens.json');
const out = path.join(root, 'css', 'bureau.css');
const tokens = JSON.parse(fs.readFileSync(src, 'utf8'));

const MOTION = {
  duration: [
    ['instant', '80ms', 'Hover, focus, press feedback.'],
    ['fast', '140ms', 'Chips, toggles, tabs, small fades.'],
    ['base', '220ms', 'Drawers, toasts, accordions, card hover.'],
    ['slow', '360ms', 'Modals, page-level crossfades, office camera moves.'],
  ],
  ease: [
    ['standard', 'cubic-bezier(0.2, 0, 0, 1)', 'Default for anything that moves or changes on screen.'],
    ['enter', 'cubic-bezier(0.05, 0.7, 0.1, 1)', 'Elements arriving: toasts, drawers, modals.'],
    ['exit', 'cubic-bezier(0.3, 0, 0.8, 0.15)', 'Elements leaving; pair with a shorter duration.'],
    ['linear', 'linear', 'Progress bars, spinners, the live pulse.'],
  ],
};

// ---------- validation (fail loudly; the token file is the contract) ----------
const NAME = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$/;
const VALUE_COLOR = /^(#[0-9A-Fa-f]{3,8}|rgba?\([^)]*\)|hsla?\([^)]*\)|oklch\([^)]*\)|\{[A-Za-z0-9][A-Za-z0-9_.-]{0,63}\})$/;
const errors = [];
const seen = new Set();
const familyNames = Object.keys(tokens).filter((k) => k !== 'type');
for (const fam of familyNames) {
  const list = tokens[fam]?.tokens;
  if (!Array.isArray(list)) { errors.push(`${fam}: "tokens" must be a list`); continue; }
  for (const t of list) {
    if (!NAME.test(t.name)) errors.push(`${fam}: bad name "${t.name}"`);
    if (seen.has(t.name)) errors.push(`${fam}: duplicate name "${t.name}"`);
    seen.add(t.name);
    if (!t.usage || t.usage.length < 8) errors.push(`${fam}/${t.name}: missing usage note`);
    const vals = fam === 'color' ? Object.values(t.value || {}) : [t.value];
    for (const v of vals) {
      if (typeof v !== 'string') { errors.push(`${fam}/${t.name}: value must be a string`); continue; }
      if (/var\(|color-mix\(/.test(v)) errors.push(`${fam}/${t.name}: var()/color-mix() not allowed`);
      if (fam === 'color' && !VALUE_COLOR.test(v)) errors.push(`${fam}/${t.name}: "${v}" is not hex/rgb/hsl/oklch/alias`);
    }
    if (fam === 'color' && !(t.value?.dark && t.value?.light)) errors.push(`color/${t.name}: needs dark and light`);
  }
}
const themes = tokens.color?.themes?.map((t) => t.id) || [];
if (themes.join() !== 'dark,light') errors.push('color.themes must be dark, light');
for (const g of tokens.type?.groups || []) {
  if (!tokens.type.families[g.family]) errors.push(`type/${g.name}: unknown family ${g.family}`);
  for (const s of g.styles) {
    if (!NAME.test(s.name)) errors.push(`type: bad style name ${s.name}`);
    if (seen.has(s.name)) errors.push(`type: duplicate name ${s.name}`);
    seen.add(s.name);
  }
}
if (errors.length) { console.error('tokens.json is invalid:\n  ' + errors.join('\n  ')); process.exit(1); }

// ---------- helpers ----------
const resolve = (v, theme, fam) => {
  const m = typeof v === 'string' && v.match(/^\{(.+)\}$/);
  if (!m) return v;
  const target = (tokens[fam]?.tokens || []).find((t) => t.name === m[1]);
  if (!target) throw new Error(`alias ${v} not found in ${fam}`);
  return `var(--bu-${target.name})`;
};
const decl = (name, value, note) => `  --bu-${name}: ${value};${note ? ` /* ${note.replace(/\*\//g, '')} */` : ''}`;
const fontStack = {
  display: `"${tokens.type.families.display}", "Inter", system-ui, sans-serif`,
  sans: `"${tokens.type.families.sans}", system-ui, -apple-system, "Segoe UI", sans-serif`,
  mono: `"${tokens.type.families.mono}", ui-monospace, "SF Mono", Menlo, monospace`,
};
const short = (u) => (u || '').split(/(?<=\.)\s/)[0].slice(0, 90);

// ---------- build ----------
const L = [];
L.push('/* Bureau — design tokens for Agent Office.');
L.push(' * GENERATED by design/scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */');
const fams = tokens.type.families;
// Self-hosted fonts (PM decision on frontend-16): no third-party request. design/fonts/fonts.json lists the woff2
// subsets of the variable fonts; the files ship next to this stylesheet (public/v2/bureau/fonts/, sync-design.js).
const FONTS = JSON.parse(fs.readFileSync(path.join(root, 'fonts', 'fonts.json'), 'utf8')).fonts;
for (const fam of [fams.display, fams.sans, fams.mono]) if (!FONTS.some((f) => f.family === fam)) throw new Error(`no self-hosted font for ${fam} (design/fonts/fonts.json)`);
L.push('/* Fonts: SIL Open Font License 1.1, see fonts/OFL-*.txt. Variable weights 400–700, one file per subset. */');
for (const f of FONTS) {
  L.push(`@font-face { font-family: "${f.family}"; font-style: normal; font-weight: ${f.weights[0]} ${f.weights[1]}; font-display: swap;`);
  L.push(`  src: url("fonts/${f.file}") format("woff2"); unicode-range: ${f.unicodeRange}; }`);
}
L.push('');

L.push(':root {');
L.push('  /* type families */');
for (const [k, v] of Object.entries(fontStack)) L.push(decl(`font-${k}`, v));
L.push('  /* type roles: --bu-type-<style> is a `font` shorthand; size/line/weight are also exposed */');
for (const g of tokens.type.groups) {
  for (const s of g.styles) {
    L.push(decl(`type-${s.name}`, `${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--bu-font-${g.family})`));
    L.push(decl(`type-${s.name}-size`, s.fontSize));
    L.push(decl(`type-${s.name}-line`, s.lineHeight));
    L.push(decl(`type-${s.name}-weight`, String(s.fontWeight)));
  }
}
L.push(decl('tracking-label', '0.04em', 'uppercase label/eyebrow tracking'));
L.push(decl('tracking-display', '-0.01em', 'Sora display/title tracking'));
for (const fam of familyNames.filter((f) => f !== 'color')) {
  L.push(`  /* ${fam} */`);
  for (const t of tokens[fam].tokens) L.push(decl(t.name, resolve(t.value, null, fam), short(t.usage)));
}
L.push('  /* motion (see README § Mouvement) */');
for (const [n, v, u] of MOTION.duration) L.push(decl(`duration-${n}`, v, u));
for (const [n, v, u] of MOTION.ease) L.push(decl(`ease-${n}`, v, u));
L.push('}');
L.push('');

const colorBlock = (theme, indent = '  ') => tokens.color.tokens.map((t) => `${indent}--bu-${t.name}: ${resolve(t.value[theme], theme, 'color')};`).join('\n');
L.push('/* colour — dark is the default theme */');
L.push(':root,\n[data-theme="dark"] {');
L.push('  color-scheme: dark;');
L.push(colorBlock('dark'));
L.push('}');
L.push('');
L.push('@media (prefers-color-scheme: light) {');
L.push('  :root:not([data-theme="dark"]) {');
L.push('    color-scheme: light;');
L.push(colorBlock('light', '    '));
L.push('  }');
L.push('}');
L.push('');
L.push('[data-theme="light"] {');
L.push('  color-scheme: light;');
L.push(colorBlock('light'));
L.push('}');
L.push('');
L.push('@media (prefers-reduced-motion: reduce) {');
L.push('  :root {');
for (const [n] of MOTION.duration) L.push(`    --bu-duration-${n}: 0.01ms;`);
L.push('  }');
L.push('}');
L.push('');

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, L.join('\n'));
const nColor = tokens.color.tokens.length;
const nOther = familyNames.filter((f) => f !== 'color').reduce((n, f) => n + tokens[f].tokens.length, 0);
const nType = tokens.type.groups.reduce((n, g) => n + g.styles.length, 0);
console.log(`bureau.css: ${nColor} colours × 2 themes, ${nOther} other tokens, ${nType} type styles, ${MOTION.duration.length + MOTION.ease.length} motion → ${path.relative(process.cwd(), out)}`);
