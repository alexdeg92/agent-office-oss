#!/usr/bin/env node
// Builds public/v2/icons.js: the Lucide inline SVG sprite used by the /v2 UI.
// Usage: node design/scripts/build-icons.mjs <path to lucide-static/icons>
//   (get it with `npm pack lucide-static@<version>` and extract; nothing is installed in the repo).
// Each Bureau icon name maps to one Lucide icon (README §4: one icon per concept). Plain Node, no deps.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const LUCIDE_VERSION = '1.52.0';

// Bureau name → Lucide file name.
const ICONS = {
  // navigation (README §4)
  bureau: 'building-2', discuter: 'message-square', flux: 'workflow', projets: 'square-kanban',
  habilitations: 'shield-check', journaux: 'scroll-text', competences: 'blocks', sante: 'activity',
  plus: 'ellipsis', agent: 'bot', personne: 'user', canal: 'hash', commit: 'git-commit-horizontal',
  branche: 'git-branch', risque: 'triangle-alert', drapeau: 'flag',
  // agent states (README §4)
  'state-idle': 'pause', 'state-thinking': 'sparkles', 'state-working': 'zap', 'state-researching': 'search',
  'state-writing': 'pen-line', 'state-calling': 'plug', 'state-waiting': 'hourglass', 'state-error': 'circle-alert',
  'state-offline': 'moon',
  // status and UI
  alert: 'circle-alert', warning: 'triangle-alert', success: 'circle-check', info: 'info', error: 'circle-x',
  close: 'x', refresh: 'refresh-cw', 'chevron-right': 'chevron-right', 'chevron-left': 'chevron-left',
  logout: 'log-out', login: 'log-in', sun: 'sun', moon: 'moon', monitor: 'monitor',
  cpu: 'cpu', memory: 'memory-stick', disk: 'hard-drive', gauge: 'gauge', clock: 'clock', server: 'server',
  plug: 'plug', database: 'database', 'bell-off': 'bell-off', bell: 'bell', 'wifi-off': 'wifi-off',
  layers: 'layers', list: 'list',
  search: 'search', add: 'plus', 'arrow-right': 'arrow-right', 'arrow-left': 'arrow-left', 'arrow-down': 'arrow-down', langue: 'languages', external: 'external-link', folder: 'folder', check: 'check',
  boutique: 'shopping-bag', pencil: 'pencil', link: 'link', grip: 'grip-vertical', 'git-pr': 'git-pull-request', eye: 'eye', undo: 'undo-2', import: 'download', filter: 'list-filter',
  'tool-search': 'search', 'tool-web': 'globe', 'tool-browser': 'app-window', 'tool-exec': 'terminal', 'tool-file-read': 'file-text',
  'tool-file-write': 'file-pen-line', 'tool-memory': 'brain', 'tool-message': 'send', 'tool-image': 'image', 'tool-other': 'wrench', system: 'cog',
};

const dir = process.argv[2];
if (!dir) { console.error('usage: build-icons.mjs <lucide-static/icons dir>'); process.exit(2); }

const symbols = [];
for (const [name, file] of Object.entries(ICONS)) {
  const svg = readFileSync(join(dir, file + '.svg'), 'utf8');
  const body = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '').replace(/\s*\/>/g, '/>').trim();
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`);
}

const out = `// GENERATED by design/scripts/build-icons.mjs from lucide-static ${LUCIDE_VERSION} (ISC, see vendor/licenses/lucide.LICENSE).
// Do not edit by hand. Stroke width, caps and colour come from .bu-icon in bundle.css.
export const ICON_NAMES = ${JSON.stringify(Object.keys(ICONS))};
export const SPRITE = ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" class="ao-sprite" aria-hidden="true">${symbols.join('')}</svg>`)};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '../../public/v2/icons.js');
writeFileSync(target, out);
console.log(`icons.js: ${symbols.length} icons → ${target}`);
