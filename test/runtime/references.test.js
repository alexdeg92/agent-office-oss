'use strict';
const { test } = require('node:test'), assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { openStore } = require('../../src/store');
const { scopedId } = require('../../src/runtime-ids');
const { openDatabase, MIGRATIONS_DIR } = require('../../src/store/db');
const { createPersonsRepo } = require('../../src/store/repos/persons');
const { createRuntimeReferences } = require('../../src/store/runtime-references');
test('pre-019 repositories retain native identities; namespace writes require migration and preserve identity on upgrade', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ao-runtime-upgrade-'));
  const migrationsDir = path.join(dir, 'migrations'); fs.mkdirSync(migrationsDir);
  for (const file of fs.readdirSync(MIGRATIONS_DIR)) if (Number(file.slice(0, 3)) <= 18)
    fs.copyFileSync(path.join(MIGRATIONS_DIR, file), path.join(migrationsDir, file));
  const options = { dir: path.join(dir, 'data'), instance: 'test' };
  let handle = openDatabase({ ...options, migrationsDir });
  t.after(() => { handle?.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  const person = createPersonsRepo(handle.db).ensureAgent('atlas', 'Synthetic agent').person;
  handle.db.prepare('INSERT INTO api_tokens VALUES(?,?,?,?,?,?)').run('tok_fixture', 'a'.repeat(64), 'atlas', 'projects-agent', 123, null);
  const tokenBefore = handle.db.prepare('SELECT * FROM api_tokens').get();
  const refs = createRuntimeReferences(handle.db);
  const native = { actor: { kind: 'agent', agentId: 'atlas' }, sessionKey: 'native-session' };
  assert.equal(refs.active(), false); assert.equal(refs.adapterFor('legacy'), null);
  assert.deepEqual(refs.project(native), native);
  assert.throws(() => refs.bind([{ id: 'legacy', adapter: 'openclaw' }]), { code: 'EMIGRATION' });
  assert.throws(() => refs.migrate('b'.repeat(64)), { code: 'EMIGRATION' });
  assert.equal(handle.db.prepare("SELECT 1 FROM sqlite_master WHERE name='runtime_instance_bindings'").get(), undefined);
  assert.deepEqual(handle.db.prepare('SELECT * FROM api_tokens').get(), tokenBefore);
  assert.equal(createPersonsRepo(handle.db).list().find(p => p.id === person.id).links.agentId, 'atlas');
  handle.close(); handle = null;
  handle = openDatabase(options);
  assert.ok(handle.applied.includes(19)); assert.ok(handle.applied.includes(20));
  const upgraded = createRuntimeReferences(handle.db);
  assert.equal(upgraded.migrate('b'.repeat(64)), true);
  upgraded.bind([{ id: 'legacy', adapter: 'openclaw' }]);
  assert.equal(upgraded.adapterFor('legacy'), 'openclaw');
  assert.throws(() => upgraded.bind([{ id: 'legacy', adapter: 'claude-code' }]), { code: 'EIDENTITY' });
  assert.equal(createPersonsRepo(handle.db).list().find(p => p.id === person.id).links.agentId, scopedId('legacy', 'agent', 'atlas'));
  assert.deepEqual({ ...handle.db.prepare('SELECT * FROM api_tokens').get() }, { ...tokenBefore, agent_id: scopedId('legacy', 'agent', 'atlas') });
  assert.equal(upgraded.project(native).sessionKey, scopedId('legacy', 'session', 'native-session'));
});
test('runtime migration preserves Person IDs and token hashes, scopes seating and projects immutable links on read', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ao-runtime-links-'));
  const store = openStore({ dir, instance: 'test', ownerName: 'Synthetic operator' });
  t.after(() => { store.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  const person = store.persons.ensureAgent('atlas', 'Synthetic agent').person;
  store.db.prepare('INSERT INTO api_tokens VALUES(?,?,?,?,?,?)').run('tok_fixture', 'a'.repeat(64), 'atlas', 'projects-agent', 123, null);
  store.office.active(() => ({ agents: [{ agentId: 'agent:atlas', name: 'Synthetic agent' }] }));
  store.office.seen([{ id: 'agent:atlas', role: 'agent', name: 'Synthetic agent' }], 123);
  const index = require('../../public/v2/office/assets.js').indexManifest(require('../../design/office/manifest.example.json'));
  const savedLook = store.office.automaticLook('agent:atlas', index);
  const native = { kind: 'session', sessionKey: 'native-session', at: 123, dedupeKey: 'session:native-session@123', actor: { kind: 'agent', agentId: 'atlas' }, body: 'atlas' };
  assert.deepEqual(store.runtimeReferences.project(native), native);
  assert.equal(store.runtimeReferences.migrate('b'.repeat(64)), true);
  assert.equal(store.runtimeReferences.migrate('c'.repeat(64)), false);
  assert.equal(store.persons.list().find(p => p.id === person.id).links.agentId, scopedId('legacy', 'agent', 'atlas'));
  const token = store.db.prepare('SELECT * FROM api_tokens').get();
  assert.equal(token.hash, 'a'.repeat(64)); assert.equal(token.agent_id, scopedId('legacy', 'agent', 'atlas')); assert.equal(token.revoked_at, null);
  assert.equal(store.office.active().data.agents[0].agentId, 'agent:' + scopedId('legacy', 'agent', 'atlas'));
  assert.deepEqual(store.office.automaticLook('agent:' + scopedId('legacy', 'agent', 'atlas'), index), savedLook);
  assert.equal(store.db.prepare('SELECT count(*) AS n FROM office_automatic_looks').get().n, 1);
  const projected = store.runtimeReferences.project(native);
  assert.equal(projected.sessionKey, scopedId('legacy', 'session', 'native-session'));
  assert.equal(projected.actor.agentId, scopedId('legacy', 'agent', 'atlas'));
  assert.equal(projected.body, 'atlas'); assert.equal(native.sessionKey, 'native-session');
  assert.deepEqual(store.runtimeReferences.project(projected), projected);
});
