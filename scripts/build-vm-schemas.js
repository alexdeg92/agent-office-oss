#!/usr/bin/env node
'use strict';
/*
 * Builds the SHARED VM schema module for the frontend (PM audit (B), part 3): one browser ES module
 * (public/v2/generated/vm-schemas.js) bundling the schema DSL and the VM schemas the server validates against, so the
 * UI can validate every incoming VM in dev and test with exactly the same rules:
 *
 *   import { validateVM } from './generated/vm-schemas.js';
 *   const r = validateVM('office', vm);   // { ok: true } | { ok: false, issues: [{ path, detail }] }
 *
 * No dependency: the CommonJS sources are wrapped in functions with a tiny require map. Run after changing
 * src/schema or src/api/v2/vm/schemas.js; test/core/vm-schemas-module.test.js fails when the file is stale.
 *   node scripts/build-vm-schemas.js [--check]
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'public', 'v2', 'generated', 'vm-schemas.js');
const MODULES = [   // [id, file, { requirePath: id }]
  ['schema', 'src/schema/index.js', {}],
  ['vm-schemas', 'src/api/v2/vm/schemas.js', { '../../../schema': 'schema' }],
];

function build() {
  const parts = ['// GENERATED by scripts/build-vm-schemas.js from src/schema and src/api/v2/vm/schemas.js. Do not edit.',
    '// The same schemas the server validates every VM against (PM audit (B)); use validateVM() in dev and test.',
    'const __defs = {};', 'const __cache = {};',
    'function __require(id) { if (!(id in __cache)) { const module = { exports: {} }; __cache[id] = module.exports; __defs[id](module, module.exports); __cache[id] = module.exports; } return __cache[id]; }'];
  for (const [id, file, map] of MODULES) {
    let src = fs.readFileSync(path.join(ROOT, file), 'utf8');
    // rewrite code requires only (a require() inside a comment is documentation)
    src = src.split('\n').map((line) => (/^\s*(\*|\/\/|\/\*)/.test(line) ? line : line.replace(/require\((['"])([^'"]+)\1\)/g, (m, q, p) => {
      if (!(p in map)) throw new Error(file + ': unexpected require ' + p);
      return '__require(' + JSON.stringify(map[p]) + ')';
    }))).join('\n');
    parts.push(`__defs[${JSON.stringify(id)}] = function (module, exports) {\n${src}\n};`);
  }
  parts.push(`const __s = __require('schema');
const __vm = __require('vm-schemas');
export const VM_SCHEMAS = __vm.VM_SCHEMAS;
// G5: contract 3.0's schemas (api-v3.md); validateVM(name, vm, 3) checks a /api/v3 VM
export const VM_SCHEMAS_V3 = __vm.VM_SCHEMAS_V3;
// The first path holding undefined (never allowed in a VM), or null.
function undefinedPath(v, p = '$') {
  if (v === undefined) return p;
  if (v === null || typeof v !== 'object') return null;
  if (Array.isArray(v)) { for (const x of v) { const r = undefinedPath(x, p + '[]'); if (r) return r; } return null; }
  for (const k of Object.keys(v)) { const r = undefinedPath(v[k], p + '.' + k); if (r) return r; }
  return null;
}
/** → { ok: true } | { ok: false, issues: [{ path, detail }] } (value-free) */
export function validateVM(name, vm, version = 2) {
  const schema = (version === 3 ? VM_SCHEMAS_V3 : VM_SCHEMAS)[name];
  if (!schema) return { ok: false, issues: [{ path: '$', detail: 'no schema for ' + name }] };
  const u = undefinedPath(vm);
  if (u) return { ok: false, issues: [{ path: u, detail: 'undefined value' }] };
  const r = __s.validate(schema, vm);
  const issues = r.ok ? [] : r.issues.filter((i) => i.severity === 'error').map((i) => ({ path: i.path, detail: i.detail }));
  return issues.length ? { ok: false, issues } : { ok: true };
}
`);
  return parts.join('\n') + '\n';
}

if (require.main === module) {
  const out = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) { process.stderr.write('vm-schemas.js is stale: run node scripts/build-vm-schemas.js\n'); process.exit(1); }
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, out);
    process.stdout.write('wrote ' + path.relative(ROOT, OUT) + '\n');
  }
}
module.exports = { build, OUT };
