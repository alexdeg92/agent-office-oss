#!/usr/bin/env node
'use strict';
// Rebuild synthetic Store examples/mock responses from the canonical projection.
const fs = require('node:fs'),path = require('node:path');
const root = path.join(__dirname,'..');
const { officeDefaults } = require('../src/api/v2/vm/office');
const { buildOfficeStoreVM } = require('../src/api/v2/vm/office-store');
const { createVmCheck } = require('../src/api/v2/vm/check');
const index = officeDefaults().index;
const office = {rosterFloors:[{id:'rdc',label:{key:'office.floor.rdc'}},{id:'1',label:{key:'office.floor.first'}},
  {id:'2',label:{key:'office.floor.number',params:{n:2}}},{id:'gym',label:{key:'office.floor.gym'}}]};
const build = (section,category='') => buildOfficeStoreVM({office,index,section,category});
const write = (file,value) => {const full=path.join(root,file);fs.mkdirSync(path.dirname(full),{recursive:true});fs.writeFileSync(full,JSON.stringify(value,null,2)+'\n');};
const example = build('mobilier');
const sidecar = { $comment:'OfficeStoreVM (api.md §3.16), identical v2/v3 projection.',types:{'$.floors.options[].count':'number'},
  nullable:['$.categoryId','$.categories','$.floors'] };
for (const [version,dir] of [[2,'docs/architecture/examples'],[3,'docs/architecture/examples/v3']]) {
  createVmCheck({mode:'throw',version}).check('officeStore',example);
  write(dir+'/office-store-vm.json',{data:example,meta:{modelVersion:1,generatedAt:1791888000000,stale:[]}});write(dir+'/office-store-vm.types.json',sidecar);
}
const catalog = {};
for (const option of example.sections.options) {
  const vm = build(option.id);catalog[option.id]={'':vm};
  for (const category of vm.categories?.options || []) if(category.id)catalog[option.id][category.id]=build(option.id,category.id);
}
write('public/v2/mock/examples/office-store-catalog.json',catalog);
const labels = language => Object.fromEntries(Object.entries(require('../src/i18n/'+language).LABELS).filter(([key])=>key.startsWith('office.store.')));
fs.writeFileSync(path.join(root,'public/v2/office/store-labels.js'),
  '// Store-owned labels; generated by build-office-store-examples.js.\nimport { LABELS_EN } from \'../locales/labels.en.js\';\n'+
  'export const fr = '+JSON.stringify(labels('fr'),null,2)+';\nexport const en = '+JSON.stringify(labels('en'),null,2)+';\nObject.assign(LABELS_EN,en);\n');
console.log('Office Store examples and mock projections rebuilt.');
