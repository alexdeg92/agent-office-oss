#!/usr/bin/env node
'use strict';
// Prints every raw schema as field tables into docs/architecture/generated/raw-schemas.md.
//   node scripts/schemas-doc.js          (rerun after changing src/adapters/*/schemas/* or src/engine/schemas/*; review the diff)
const fs = require('fs');
const path = require('path');
const { DEFAULT_SCHEMAS } = require('../src/engine');

const rows = [];
function walk(sch, p) {
  const type = sch.describe();
  if (sch.shape) {
    if (p !== '$') rows.push([p, 'object' + (sch.isOptional ? '?' : '') + (sch.isNullable ? '|null' : ''), sch.known && sch.known.length ? `known: ${sch.known.length} more` : '']);
    for (const [k, f] of Object.entries(sch.shape)) walk(f, p + '.' + k);
    return;
  }
  if (sch.item && sch.kind.startsWith('array')) { rows.push([p, type, sch.perItem ? 'per item: bad rows dropped' : '']); return walk(sch.item, p + '[]'); }
  if (sch.item) { rows.push([p, type, '']); return walk(sch.item, p + '.*'); }
  if (sch.options) { rows.push([p, type, '']); return; }
  rows.push([p, type, sch.kind === 'unknown' ? 'opaque (see schema comment)' : '']);
}

function render() {
const out = ['# Raw schemas (generated)', '', 'Generated by `node scripts/schemas-doc.js` from `src/adapters/<runtime>/schemas/` and `src/engine/schemas/`. Do not edit by hand.', ''];
for (const [channel, def] of Object.entries(DEFAULT_SCHEMAS).sort()) {
  rows.length = 0; walk(def.schema, '$');
  out.push(`## \`${channel}\` v${def.version}`, '', `${def.testedWith ? 'Tested with OpenClaw ' + def.testedWith.join(', ') : 'Core schema (runtime-independent)'}. Undeclared fields: \`${def.schema.extra || 'n/a'}\`${def.schema.known && def.schema.known.length ? `; ${def.schema.known.length} known fields kept unreported` : ''}.`, '');
  if (rows.length) { out.push('| path | type | note |', '| --- | --- | --- |'); for (const r of rows) out.push(`| \`${r[0]}\` | \`${r[1].replace(/\|/g, '\\|')}\` | ${r[2]} |`); }
  out.push('');
}
return out.join('\n');
}

const FILE = path.join(__dirname, '..', 'docs', 'architecture', 'generated', 'raw-schemas.md');
if (require.main === module) {
  fs.mkdirSync(path.dirname(FILE), { recursive: true });
  fs.writeFileSync(FILE, render());
  console.log('wrote ' + path.relative(process.cwd(), FILE));
}
module.exports = { render, FILE };
